import { describe, expect, it } from "vitest";
import fs from "node:fs";
import path from "node:path";
import robots from "../../src/app/robots";

const root = path.resolve(__dirname, "../..");
const read = (relative: string) => fs.readFileSync(path.join(root, relative), "utf8");

describe("MR-10J prelaunch metadata and crawler policy", () => {
  it("replaces starter branding with accurate internal MPG Reputation defaults", () => {
    const layout = read("src/app/layout.tsx");
    expect(layout).toContain('applicationName: "MPG Reputation"');
    expect(layout).toContain('title: "MPG Reputation | Internal Preview"');
    expect(layout).toContain("responsible review-request workflows");
    expect(layout).not.toMatch(/Create Next App|Generated by create next app/i);
  });

  it("sets a fail-closed root noindex policy, including pages without metadata overrides", () => {
    const layout = read("src/app/layout.tsx");
    expect(layout).toContain("robots: { index: false, follow: false, nocache: true }");
    expect(layout).not.toMatch(/robots:\s*\{[^}]*index:\s*true/);
  });

  it("preserves non-indexable public marketing routes and article metadata", () => {
    const routes = [
      "",
      "features",
      "how-it-works",
      "pricing",
      "faq",
      "trust",
      "resources",
      "reputation-check",
      "reputation-report",
    ];
    for (const route of routes) {
      const file = `src/app/${route ? route + "/" : ""}page.tsx`;
      const source = read(file);
      expect(source, file).toContain("index: false");
      expect(source, file).toContain("follow: false");
    }
    const article = read("src/app/resources/[slug]/page.tsx");
    expect(article).toContain("robots: { index: false, follow: false }");
  });

  it("makes noindex readable to crawlers rather than blocking it through robots.txt", () => {
    expect(robots()).toEqual({
      rules: { userAgent: "*", allow: "/" },
    });
    expect(robots()).not.toHaveProperty("sitemap");
    expect(robots()).not.toHaveProperty("host");
  });

  it("keeps the generated robots route outside the auth proxy while retaining protected routes", () => {
    const proxy = read("src/proxy.ts");
    const matcherSource = proxy.match(/matcher:\s*\[\s*'([^']+)'/);
    expect(matcherSource).not.toBeNull();
    const matcher = new RegExp(matcherSource![1]);
    expect(matcher.test("/robots.txt")).toBe(false);
    expect(matcher.test("/favicon.ico")).toBe(false);
    expect(matcher.test("/app")).toBe(true);
    expect(matcher.test("/login")).toBe(true);
    expect(proxy).toContain("supabase.auth.getUser()");
    expect(proxy).toContain("pathname.startsWith('/app')");
    expect(proxy).toContain("pathname.startsWith('/onboarding')");
  });

  it("does not invent a live canonical domain, sitemap, or public launch approval", () => {
    const layout = read("src/app/layout.tsx");
    expect(layout).not.toMatch(/metadataBase|alternates:\s*\{|canonical:\s*['"]/);
    expect(fs.existsSync(path.join(root, "src/app/sitemap.ts"))).toBe(false);
    expect(fs.existsSync(path.join(root, "src/app/sitemap.xml"))).toBe(false);
    expect(fs.existsSync(path.join(root, "public/sitemap.xml"))).toBe(false);
  });

  it("preserves the production 404 guard on internal campaign preview", () => {
    const preview = read("src/app/mr10-campaign-preview/page.tsx");
    expect(preview).toContain('process.env.NODE_ENV !== "development"');
    expect(preview).toContain("notFound()");
    expect(preview).toContain("index: false, follow: false, nocache: true");
  });
});
