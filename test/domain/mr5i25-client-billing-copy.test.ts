import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { describe, expect, it, vi } from 'vitest'

vi.mock('next/link', async () => {
  const { createElement } = await import('react')
  return {
    default: ({ href, children }: { href: string; children: unknown }) =>
      createElement('a', { href }, children as string),
  }
})
vi.mock('@/actions/usage', () => ({
  startOrganizationTrialAction: vi.fn(),
  provisionOrganizationTrialAction: vi.fn(),
}))

import { UsageClient } from '../../src/app/app/settings/usage/client'

const syntheticUsage = {
  entitlement: {
    status: 'NOT_STARTED',
    effectiveStatus: 'NOT_STARTED',
    allocatedRequests: 30,
    consumedRequests: 0,
    remainingRequests: 30,
    durationDays: 30,
  },
  ledgerCounts: {
    initialRequestsCreated: 0,
    remindersCreated: 0,
    providerSendAttempts: 0,
    providerSendSuccesses: 0,
    providerSendFailures: 0,
    trackedClicks: 0,
  },
  recentEvents: [],
  canStartTrial: true,
}

function renderTrial(role: string) {
  return renderToStaticMarkup(createElement(UsageClient, {
    organizationId: '11111111-1111-4111-8111-111111111111',
    userRole: role,
    initialUsage: syntheticUsage as never,
  }))
}

describe('MR-5I25 customer-facing trial and billing copy', () => {
  it('replaces Create Next App metadata with the product name', () => {
    const root = readFileSync(resolve(__dirname, '../../src/app/layout.tsx'), 'utf8')
    expect(root).toContain('title: "MPG Reputation"')
    expect(root).not.toContain('Create Next App')
    expect(root).not.toContain('Generated by create next app')
  })

  it('explains free-trial allowance without internal milestone labels or delivery guarantees', () => {
    const html = renderTrial('VIEWER')
    expect(html).toContain('About your free trial')
    expect(html).toContain('Trial review-request allowance')
    expect(html).toContain('Review requests used')
    expect(html).toContain('not a paid subscription')
    expect(html).toContain('Trial activation does not')
    expect(html).not.toContain('Validation Hypothesis')
    expect(html).not.toContain('MPG-DEC-')
    expect(html).not.toContain('Review automation is now active')
    expect(html).not.toContain('Start Trial</button>')
    expect(html).not.toContain('Configure Entitlement Allowance')
  })

  it('retains the owner-only trial activation button with no automatic activation', () => {
    const html = renderTrial('OWNER')
    expect(html).toContain('Start Trial</button>')
    expect(html).toContain('30')
    expect(html).toContain('not a paid subscription')
  })

  it('does not expose internal engineering banner copy on the customer billing page', () => {
    const billingPage = readFileSync(
      resolve(__dirname, '../../src/app/app/settings/billing/page.tsx'),
      'utf8',
    )
    expect(billingPage).toContain('Billing not yet available')
    expect(billingPage).toContain('Payments, checkout and subscription changes are disabled.')
    expect(billingPage).not.toContain('Engineering preview</span>')
  })
})
